#!/usr/bin/env python3
"""Write js/core/world-names.js: the fictional name pools used to generate overseas squads (scripts/overseas_names.py)
so the game can generate depth players, youth and promoted clubs' squads with country-appropriate names."""
import json, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from overseas_names import POOLS, DOUBLE_SURNAME

ROOT = Path(__file__).resolve().parent.parent
pools = {k: [v[0], v[1]] for k, v in POOLS.items() if k != 'BASQUE'}
text = ("'use strict';\n// Generated by scripts/build-world-names.py from scripts/overseas_names.py. Fictional first names and surnames by nationality.\n"
        "const WORLD_NAME_POOLS = " + json.dumps(pools, ensure_ascii=False, separators=(',', ':')) + ";\n"
        "const WORLD_DOUBLE_SURNAME = new Set(" + json.dumps(sorted(DOUBLE_SURNAME - {'BASQUE'})) + ");\n")
(ROOT / 'js/core/world-names.js').write_text(text, encoding='utf-8')
print(len(pools), 'pools,', len(text) // 1024, 'KB')
